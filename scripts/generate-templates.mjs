import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = 'src/generated/templates.ts';

const TEMPLATES = [
  {
    id: 'blank',
    name: 'Blank document',
    description: 'Start with an empty page',
    file: 'assets/documents/blank.docx',
  },
  {
    id: 'report',
    name: 'Report',
    description: 'Title, introduction, findings, conclusion',
    file: 'assets/documents/templates/report.docx',
  },
  {
    id: 'letter',
    name: 'Letter',
    description: 'Date, address block, greeting, closing',
    file: 'assets/documents/templates/letter.docx',
  },
  {
    id: 'resume',
    name: 'Resume',
    description: 'Name, experience, education, skills',
    file: 'assets/documents/templates/resume.docx',
  },
  {
    id: 'notes',
    name: 'Notes',
    description: 'Titled page for quick notes',
    file: 'assets/documents/templates/notes.docx',
  },
];

const entries = TEMPLATES.map((template) => {
  const base64 = readFileSync(template.file).toString('base64');
  return (
    '  {\n' +
    `    id: '${template.id}',\n` +
    `    name: '${template.name}',\n` +
    `    description: '${template.description}',\n` +
    `    base64:\n      ${JSON.stringify(base64)},\n` +
    '  }'
  );
});

mkdirSync('src/generated', { recursive: true });
writeFileSync(
  OUT,
  '// AUTO-GENERATED by scripts/generate-templates.mjs - do not edit.\n' +
    'export type TemplateId =\n' +
    TEMPLATES.map((t) => `  | '${t.id}'`).join('\n') +
    ';\n\n' +
    'export interface TemplateDef {\n' +
    '  id: TemplateId;\n' +
    '  name: string;\n' +
    '  description: string;\n' +
    '  base64: string;\n' +
    '}\n\n' +
    'export const TEMPLATES: TemplateDef[] = [\n' +
    entries.join(',\n') +
    ',\n];\n',
);

const kb = (readFileSync(OUT).length / 1024).toFixed(1);
console.log(`Wrote ${OUT} (${kb} KB, ${TEMPLATES.length} templates)`);
